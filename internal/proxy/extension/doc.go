// Package extension 没有生产代码，它是扩展点那条边界的守卫用例的家。
//
// 边界（spec 的「扩展点」一节）：任何「HTTP GET + 内容寻址」形态的新上游，都应当
// 只需要经管理接口加一条记录就能用——不改代码、不重启进程。这句话不写成用例就
// 只是一句愿望：它会在某次「顺手加个 host 判断」之后悄悄失效，而所有既有用例仍然
// 全绿，因为它们测的都是已经存在的那几个上游。
//
// 守卫分两处，缺一不可：
//
//   - extension_test.go：在**一个已经装配好的进程内**跑完整条路——经 HTTP 打管理
//     接口注册一个假上游，再经拉取路径拿到对象并在第二次命中缓存；
//   - scripts/smoke.sh：用 make build 出来的真二进制对同一件事再走一遍，补上
//     用例替身够不到的那一段（真配置、真 sqlite、生产的 NoRoute 处理器）。
